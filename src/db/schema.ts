import {
  boolean,
  index,
  integer,
  jsonb,
  pgEnum,
  pgTable,
  primaryKey,
  text,
  timestamp,
  uuid,
} from "drizzle-orm/pg-core";
import { user } from "./auth-schema";

export * from "./auth-schema";

// Content stays in git (content/cards/**.md); these tables hold only progress.

export const cardStateEnum = pgEnum("card_state_kind", ["new", "learning", "review", "relearning"]);
export const ratingEnum = pgEnum("rating", ["again", "hard", "good", "easy"]);
export const labStatusEnum = pgEnum("lab_status", ["started", "passed", "failed"]);

const userId = () =>
  text()
    .notNull()
    .references(() => user.id, { onDelete: "cascade" });

export const cardState = pgTable(
  "card_state",
  {
    userId: userId(),
    cardId: text().notNull(), // = content file slug, e.g. "frontend/stale-closure-interval"
    // Queryable copies of the scheduler state:
    due: timestamp({ withTimezone: true }).notNull(),
    state: cardStateEnum().notNull(),
    reps: integer().notNull().default(0),
    lapses: integer().notNull().default(0),
    lastReview: timestamp({ withTimezone: true }),
    introducedAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
    // The full ts-fsrs card (stability, difficulty, learning step, ...). Stored whole so
    // moving to a newer FSRS model doesn't need a migration for every new field.
    memory: jsonb().$type<Record<string, unknown>>().notNull(),
  },
  (t) => [
    primaryKey({ columns: [t.userId, t.cardId] }),
    // Makes "what's due today?" an index range scan.
    index().on(t.userId, t.due),
  ],
);

export const reviewLog = pgTable(
  "review_log",
  {
    // Generated by the client per answer, so a retried request can't record twice.
    id: uuid().primaryKey(),
    userId: userId(),
    cardId: text().notNull(),
    rating: ratingEnum().notNull(),
    correct: boolean(), // set for auto-graded types (mcq, what-prints, bug-hunt)
    durationMs: integer(),
    // ts-fsrs revlog: the memory state *before* this review, kept for future optimizer runs.
    revlog: jsonb().$type<Record<string, unknown>>().notNull(),
    reviewedAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index().on(t.userId, t.reviewedAt)],
);

export const labAttempt = pgTable("lab_attempt", {
  id: uuid().primaryKey().defaultRandom(),
  userId: userId(),
  labId: text().notNull(),
  status: labStatusEnum().notNull(),
  evidence: jsonb(), // what the verify check saw
  createdAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
});
